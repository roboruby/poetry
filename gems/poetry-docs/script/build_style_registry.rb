#!/usr/bin/env ruby
# frozen_string_literal: true

# poetry-docs style registry builder.
#
# Vendors the sibling gems' CSS for the docs:
#
#   - refreshes the installed slots under tailwind/poetry (the tokens, the
#     Tailwind theme mapping, the vendored layers, the gems' own
#     stylesheets, poetry/style-default.css and poetry/style-charts.css)
#     from the sibling gems, byte-verbatim - the same bytes
#     `bin/rails g poetry:install` would write, kept in sync so a future
#     installer re-run is a no-op; and
#   - writes tailwind/styles/style-<name>.css for ALL NINE
#     themes (default included), each fragment nested inside a
#     .style-<name> { ... } block - the upstream shadcn mechanism at
#     96da9cc7, the shadcn@4.23.0 release (apps/v4/app/style-registry.css imports wrapped style
#     fragments into layer(base)).
#
# The docs site deviates from a normal poetry install on purpose: an
# install carries ONE unscoped theme in the slot; the docs carry all nine
# scoped, with exactly one .style-<name> class on <html> at all times
# (server-rendered style-default, pre-paint swap from localStorage).
# Poetry fragments are complete visual layers - scoping all nine means no
# unscoped layer can leak tokens into a stamped theme. Upstream's shape is
# the same: their base tailwind.css is structural-only, every visual token
# lives in a per-style layer.
#
# Two slots stay out: poetry/base.css and poetry/typeset.css are seeded
# once and app-owned in an install, so the docs' copies are the docs' own.
# poetry/safelist.txt needs the loaded gems, so rake poetry_docs:vendored
# writes it after running this script.
#
# Idempotent. Run after bumping the gems. Do not hand-edit outputs.
#
#   ruby script/build_style_registry.rb           # write
#   ruby script/build_style_registry.rb --check   # write nothing; exit 1 and
#                                                 # list every stale file
#
# rake poetry_docs:vendored:verify runs the check in the default chain: a
# theme edit in a gem that never reached these copies used to pass every
# gate while the docs rendered the old rule.

ROOT = File.expand_path("..", __dir__)
GEMS = File.expand_path("..", ROOT)
UI_THEMES = File.join(GEMS, "poetry-ui/themes")
CHARTS_THEMES = File.join(GEMS, "poetry-charts/themes")
OUT_DIR = File.join(ROOT, "tailwind/styles")
SLOT_DIR = File.join(ROOT, "tailwind/poetry")
THEMES = %w[default vega nova mira rhea maia luma lyra sera].freeze

# Slot file => the file the installer copies into it, verbatim.
VERBATIM_SLOTS = {
  "tokens.css" => "poetry-core/tokens/tokens.css",
  "theme.css" => "poetry-core/tokens/tailwind-theme.css",
  "animate.css" => "poetry-core/vendor/tw-animate-css/tw-animate.css",
  "utilities.css" => "poetry-core/vendor/shadcn-tailwind/tailwind.css",
  "aliases.css" => "poetry-core/tokens/aliases.css",
  "charts.css" => "poetry-charts/app/assets/stylesheets/poetry-charts.css",
  "motion.css" => "poetry-motion/app/assets/stylesheets/poetry-motion.css",
  "agent.css" => "poetry-agent/app/assets/stylesheets/poetry-agent.css"
}.freeze

def fragment(dir, name)
  path = File.join(dir, "#{name}.css")
  abort "build_style_registry: missing fragment #{path}" unless File.exist?(path)
  css = File.read(path)
  # The wrapper depends on the fragments' bare-selector contract.
  %w[@import :root].each do |bad|
    abort "build_style_registry: #{path} breaks the bare-selector contract (#{bad})" if css.include?(bad)
  end
  css.chomp
end

def wrapped(name)
  ui = fragment(UI_THEMES, name)
  charts = fragment(CHARTS_THEMES, name)
  out = +"/* GENERATED by script/build_style_registry.rb - do not edit.\n"
  out << "   poetry #{name} theme, scope-wrapped for the docs switcher: the ui and\n"
  out << "   charts fragments from the sibling gems, nested under .style-#{name}\n"
  out << "   (upstream 96da9cc7 (shadcn@4.23.0) mechanism; MIT). Regenerate after theme changes. */\n\n"
  out << ".style-#{name} {\n#{ui}\n}\n\n"
  out << ".style-#{name} {\n#{charts}\n}\n"
  out
end

# Every file this script owns, path => the bytes it should hold.
outputs = {}

# --- slot sync (installer parity) -------------------------------------------
VERBATIM_SLOTS.each do |slot, source|
  path = File.join(GEMS, source)
  abort "build_style_registry: missing #{path}" unless File.exist?(path)
  outputs[File.join(SLOT_DIR, slot)] = File.read(path)
end
outputs[File.join(SLOT_DIR, "style-default.css")] = fragment(UI_THEMES, "default") + "\n"
outputs[File.join(SLOT_DIR, "style-charts.css")] = fragment(CHARTS_THEMES, "default") + "\n"

# --- wrapped fragments --------------------------------------------------------
THEMES.each { |name| outputs[File.join(OUT_DIR, "style-#{name}.css")] = wrapped(name) }

relative = ->(path) { path.delete_prefix("#{ROOT}/") }

if ARGV.include?("--check")
  stale = outputs.reject { |path, content| File.exist?(path) && File.read(path) == content }.keys
  if stale.empty?
    puts "style registry: #{outputs.size} vendored files match the sibling gems"
    exit 0
  end
  warn "style registry: #{stale.size} vendored file(s) no longer match the sibling gems:"
  stale.each { |path| warn "  #{relative.call(path)}" }
  exit 1
end

require "fileutils"
FileUtils.mkdir_p(OUT_DIR)
outputs.each { |path, content| File.write(path, content) }

slots = outputs.keys.select { |path| path.start_with?(SLOT_DIR) }
puts "synced slots: #{slots.map { |path| relative.call(path).delete_prefix("tailwind/") }.join(", ")}"
THEMES.each do |name|
  content = outputs.fetch(File.join(OUT_DIR, "style-#{name}.css"))
  puts "wrote styles/style-#{name}.css (#{content.scan(/^\.cn-/).size} cn rules, #{content.bytesize} bytes)"
end
puts "style registry complete: #{THEMES.size} wrapped themes"
